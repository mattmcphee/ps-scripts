                ' ______  ',
                '/\__  _\ ',
                '\/_ \ \/ ',
                '   \ \_\ ',
                '    \/_/ '
            )
            'U' = @(
                ' __   __   ',
                '/\ \  \ \  ',
                '\ \ \__\ \ ',
                ' \ \______\',
                '  \/______/'
            )
            'V' = @(
                ' __ __   ',
                '/\ \\ \  ',
                '\ \ \\ \ ',
                ' \ \____\',
                '  \/____/'
            )
            'W' = @(
                ' __ _ _   ',
                '/\ \ \ \  ',
                '\ \ \ \ \ ',
                ' \ \_____\',
                '  \/_____/'
            )
            'X' = @(
                ' ___  ___   ',
                '/\__\_\__\  ',
                '\/_/\__\_/_ ',
                ' /\__\_/\__\',
                ' \/__/ \/__/'
            )
            'Y' = @(
                ' __  __  ',
                '/\ \_\ \ ',
                '\ \__  _\',
                ' \/_/\ \/',
                '    \/_/ '
            )
