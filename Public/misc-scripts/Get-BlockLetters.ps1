function Get-BlockLetters {
    [CmdletBinding()]
    param (
        # Text
        [Parameter(Mandatory, ValueFromPipeline)]
        [string]
        $Text,
        # Colour
        [Parameter(Mandatory=$false)]
        [string]
        $Colour
    )
    
    begin {
        $asciiTable = @{
            'A' = @(
                ' ______   ',
                '/\  __ \  ',
                '\ \  __ \ ',
                ' \ \ \ \ \',
                '  \/_/\/_/'
            )
            'B' = @(
                ' _____    ',
                '/\  _ \_  ',
