                '  \/_____/'
            )
            'C' = @(
                ' ______   ',
                '/\  ___\  ',
                '\ \ \__/_ ',
                ' \ \_____\',
                '  \/_____/'
            )
            'D' = @(
                ' ______   ',
                '/\  __ \  ',
                '\ \ \_\ \ ',
                ' \ \_____\',
                '  \/_____/'
            )
            'E' = @(
                ' ______   ',
                '/\  ___\  ',
                '\ \  ___\ ',
                ' \ \_____\',
                '  \/_____/'
            )
            'F' = @(
                ' ______ ',
                '/\  ___\',
                '\ \  _\/',
                ' \ \_\/ ',
                '  \/_/  '
            )
            'G' = @(
                ' _____    ',
                '/\  __\_  ',
                '\ \ \_\ \ ',
                ' \ \__   \',
                '  \/__/\_/'
            )
            'H' = @(
                ' __  __   ',
                '/\ \_\ \  ',
                '\ \  __ \ ',
                ' \ \_\ \_\',
                '  \/_/\/_/'
            )
            'I' = @(
                ' ______   ',
                '/\__  _\  ',
                '\/__\ \__ ',
                '  /\_____\',
                '  \/_____/'
            )
            'J' = @(
                ' ____   ',
                '/\__ \  ',
                '\/__\ \ ',
                '/\_____\',
                '\/_____/'
            )
            'K' = @(
                ' __   _   ',
                '/\ \-" \  ',
                '\ \  --"_ ',
                ' \ \ \-. \',
                '  \/_/ /_/'
            )
            'L' = @(
                ' __      ',
                '/\ \     ',
                '\ \ \___ ',
                ' \ \____\',
                '  \/____/'
            )
            'M' = @(
                ' __    __   ',
                '/\ "-./  \  ',
                '\ \ \-./\ \ ',
                ' \ \_\ \ \_\',
                '  \/_/  \/_/'
            )
            'N' = @(
                ' __    __   ',
                '/\ \"-.\ \  ',
                '\ \ \"-.\ \ ',
                ' \ \_\ \ \_\',
                '  \/_/  \/_/'
            )
            'O' = @(
                ' ______   ',
                '/\  __ \  ',
                '\ \ \_\ \ ',
                ' \ \_____\',
                '  \/_____/'
            )
            'P' = @(
                ' ______  ',
                '/\  __ \ ',
                '\ \  __/ ',
                ' \ \ \/  ',
                '  \/_/   '
            )
            'Q' = @(
                ' ______  ',
                '/\  __ \ ',
                '\ \__  _\',
                ' \/_/\__\',
                '    \/__/'
            )
            'R' = @(
                ' _______  ',
                '/\  ___ \ ',
                '\ \  __ / ',
                ' \ \_\ \_\',
                '  \/_/\/_/'
            )
            'S' = @(
